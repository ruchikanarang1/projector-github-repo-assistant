import io
import zipfile
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Response
from sqlalchemy.orm import Session

from backend.app.database import get_db
from backend.app.models.project import Project, ProjectDocument
from backend.app.schemas.project import (
    DocumentResponse,
    GenerateDocRequest
)
from backend.app.services.doc_generator import DocGenerator

router = APIRouter(prefix="/api/docs", tags=["Documentation"])

DOC_TITLES = {
    "architecture": "System Architecture & Technical Design",
    "mermaid_flows": "Mermaid System & Data Flow Diagrams",
    "modules": "Codebase Directory & Module Guide",
    "tradeoffs": "Technical Decisions & Architecture Tradeoffs",
    "interview_cheatsheet": "Interview Master Cheatsheet & STAR Stories",
    "api_specs": "API Contracts, Data Models & Configuration"
}

@router.get("/{project_id}", response_model=List[DocumentResponse])
def list_project_docs(project_id: str, db: Session = Depends(get_db)):
    return (
        db.query(ProjectDocument)
        .filter(ProjectDocument.project_id == project_id)
        .order_by(ProjectDocument.created_at.asc())
        .all()
    )

@router.post("/{project_id}/generate", response_model=List[DocumentResponse])
async def generate_project_docs(
    project_id: str,
    req: GenerateDocRequest,
    db: Session = Depends(get_db)
):
    project = db.query(Project).filter(Project.id == project_id).first()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    target_types = (
        ["architecture", "mermaid_flows", "modules", "tradeoffs", "interview_cheatsheet", "api_specs"]
        if req.doc_type == "all"
        else [req.doc_type]
    )

    generated_docs = []

    for dtype in target_types:
        content = ""
        title = DOC_TITLES.get(dtype, dtype.replace("_", " ").title())

        if dtype == "architecture":
            content = await DocGenerator.generate_architecture_doc(
                project.name, project.tech_stack or [], project.file_tree or [], project.readme_content or "", req.custom_instructions
            )
        elif dtype == "mermaid_flows":
            content = await DocGenerator.generate_mermaid_diagrams(
                project.name, project.tech_stack or [], project.file_tree or []
            )
        elif dtype == "modules":
            content = await DocGenerator.generate_modules_guide(
                project.name, project.tech_stack or [], project.file_tree or []
            )
        elif dtype == "tradeoffs":
            content = await DocGenerator.generate_tradeoffs_doc(
                project.name, project.tech_stack or [], project.file_tree or []
            )
        elif dtype == "interview_cheatsheet":
            content = await DocGenerator.generate_interview_cheatsheet(
                project.name, project.tech_stack or [], project.file_tree or [], project.readme_content or ""
            )
        elif dtype == "api_specs":
            content = await DocGenerator.generate_api_specs(
                project.name, project.tech_stack or [], project.file_tree or []
            )

        doc = (
            db.query(ProjectDocument)
            .filter(ProjectDocument.project_id == project_id, ProjectDocument.doc_type == dtype)
            .first()
        )
        if doc:
            doc.content = content
            doc.title = title
        else:
            doc = ProjectDocument(
                project_id=project_id,
                doc_type=dtype,
                title=title,
                content=content
            )
            db.add(doc)

        generated_docs.append(doc)

    db.commit()
    for d in generated_docs:
        db.refresh(d)

    return generated_docs

@router.get("/{project_id}/export/zip")
def export_docs_zip(project_id: str, db: Session = Depends(get_db)):
    project = db.query(Project).filter(Project.id == project_id).first()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    docs = db.query(ProjectDocument).filter(ProjectDocument.project_id == project_id).all()
    if not docs:
        raise HTTPException(status_code=400, detail="No documentation generated yet. Generate docs first.")

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for doc in docs:
            filename = f"{doc.doc_type.upper()}.md"
            header = f"# {doc.title}\n\nProject: {project.name}\nGenerated by Projector AI\n\n---\n\n"
            z.writestr(filename, header + doc.content)

    buf.seek(0)
    filename = f"{project.name.replace(' ', '_')}_docs.zip"
    return Response(
        content=buf.getvalue(),
        media_type="application/zip",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )
